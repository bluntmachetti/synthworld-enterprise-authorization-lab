def load(path: Path):
    with path.open("rb") as fh:
        return json.load(fh)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def jdump(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def write_lines(path: Path, lines) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with path.open("w", encoding="utf-8") as fh:
        for line in lines:
            fh.write(line)
            fh.write("\n")
            n += 1
    return n


def main() -> int:
    # Verify the public artifact bytes against the published index before reading anything
    # else, so the projection can never silently run on a mutated input set.
    index = load(PUBLIC / "PUBLIC-INDEX.json")["sha256"]
    digests = {}
    for rel_path in sorted(index):
        got = sha256_file(PUBLIC / rel_path)
        digests[rel_path] = got
        if got != index[rel_path]:
            raise SystemExit(
                f"FATAL: {rel_path} sha256 {got} != PUBLIC-INDEX.json {index[rel_path]}"
            )

    universe = load(PUBLIC / "identity-access" / "identity-access-universe.json")
    kernel = load(PUBLIC / "directory-rbac" / "directory-rbac-kernel.json")
    corpus = load(PUBLIC / "evaluation-corpus" / "evaluation-corpus.json")
    abac = load(PUBLIC / "authorization" / "abac-state.json")
    authz_kernel = load(PUBLIC / "authorization" / "authorization-kernel.json")

    # ---------------------------------------------------------------- objects
    objects: list[dict] = []

    def obj(otype, oid, display, props):
        objects.append(
            {
                "object": {
                    "type": otype,
                    "id": oid,
                    "display_name": display or "",
                    "properties": {k: v for k, v in sorted(props.items()) if v is not None},
                }
            }
        )

    for t in sorted(universe["tenants"], key=lambda r: r["tenant_id"]):
        obj("tenant", t["tenant_id"], t.get("display_label"), {"tenant_id": t["tenant_id"]})

    for o in sorted(universe["organisations"], key=lambda r: r["organisation_id"]):
        obj("organisation", o["organisation_id"], o.get("display_label"),
            {"tenant_id": o["tenant_id"]})

    for u in sorted(universe["units"], key=lambda r: r["unit_id"]):
        obj("unit", u["unit_id"], u.get("display_label"), {
            "tenant_id": u["tenant_id"],
            "organisation_id": u["organisation_id"],
            "unit_kind": u.get("unit_kind"),
            "parent_unit_id": u.get("parent_unit_id"),
        })

    for g in sorted(universe["groups"], key=lambda r: r["group_id"]):
        obj("group", g["group_id"], g.get("display_label"), {
            "tenant_id": g["tenant_id"],
            "organisation_id": g["organisation_id"],
            "owner_unit_id": g["owner_unit_id"],
        })

    for r in sorted(universe["roles"], key=lambda r: r["role_id"]):
        obj("role", r["role_id"], r.get("display_label"), {
            "tenant_id": r["tenant_id"],
            "organisation_id": r["organisation_id"],
            "owner_unit_id": r["owner_unit_id"],
        })

    for t in sorted(universe["authorization_targets"], key=lambda r: r["authorization_target_id"]):
        obj("target", t["authorization_target_id"], t.get("display_label"), {
            "tenant_id": t["tenant_id"],
            "organisation_id": t["organisation_id"],
            "owner_unit_id": t["owner_unit_id"],
            "target_kind": t.get("target_kind"),
            "actions": sorted(t.get("actions") or []),
        })

    targets_by_id = {t["authorization_target_id"]: t for t in universe["authorization_targets"]}
    for p in sorted(universe["permissions"], key=lambda r: r["permission_id"]):
        tgt = targets_by_id[p["authorization_target_id"]]
        obj("permission", p["permission_id"],
            f"{tgt.get('display_label', '')} :: {p['action']}".strip(), {
                "authorization_target_id": p["authorization_target_id"],
                "action": p["action"],
            })

    principals_by_id = {p["principal_id"]: p for p in universe["principals"]}
    accounts_by_id = {a["account_id"]: a for a in universe["accounts"]}
    observations = {o["account_id"]: o for o in kernel["account_observations"]}

    for s in sorted(universe["access_subjects"], key=lambda r: r["subject_id"]):
        sid, kind = s["subject_id"], s["subject_kind"]
        props = {"subject_kind": kind, "tenant_id": s["tenant_id"]}
        display = ""
        if kind == "principal":
            p = principals_by_id[sid]
            display = p.get("display_label") or ""
            props.update({
                "principal_kind": p.get("principal_kind"),
                "organisation_id": p.get("organisation_id"),
                "unit_id": p.get("unit_id"),
            })
        else:
            a = accounts_by_id[sid]
            display = a.get("display_label") or ""
            props.update({
                "account_kind": a.get("account_kind"),
                "authorization_target_id": a.get("authorization_target_id"),
            })
            o = observations.get(sid)
            if o is not None:
                props["administrative_state"] = o["administrative_state"]
                props["valid_from_tick"] = o["valid_from_tick"]
                props["observed_principal_id"] = o["observed_principal_id"]
                props["observation_revision_id"] = o.get("revision_id")
