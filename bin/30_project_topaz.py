# --------------------------------------------------------------------------------------
# Topaz directory manifest (model version 3).
#
# Object-type choices and why:
#   subject     ONE type for both principals and accounts, because access_atoms[],
#               memberships[] and subject_role_assignments[] all key on `subject_id`, and
#               access_subjects[] is the union of principals+accounts. Splitting the type
#               would force every relation that accepts a subject to be declared twice and
#               would make `group#member` subject-sets ambiguous. `subject_kind` is carried
#               as an object property instead.
#   permission  first-class object (not a relation name), because SynthWorld's
#               permissions[] is a real entity (permission_id) that role_grants[] and
#               direct_entitlements[] both point at. Modelling it as an object is what lets
#               `exercisable` be a single closed-form permission expression.
#   role        carries `assignee` + `senior_role`; the recursive permission `holder`
#               is the role-hierarchy transitive closure, computed BY TOPAZ.
#   group       `member: subject | group#member` — the `group#member` subject-set arm is the
#               group-nesting transitive closure, computed BY TOPAZ.
#   target/unit/organisation/tenant  scoping + ownership context. Not on the decision path,
#               but required to express target ownership and tenancy faithfully.
# --------------------------------------------------------------------------------------
